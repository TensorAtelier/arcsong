/** A gradient from a seed, so every song has its own cover. */
export function artStyle(seed: number): React.CSSProperties {
  const hue = (seed * 137.508) % 360;
  return {
    background: `conic-gradient(from ${Math.round(hue)}deg, hsl(${hue} 80% 68%), hsl(${(hue + 40) % 360} 35% 38%), #2b2622, hsl(${hue} 80% 68%))`,
  };
}
